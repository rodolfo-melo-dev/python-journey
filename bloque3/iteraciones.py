# === ITERACIONES === 

# FOR -- IN


frutas = ['manzana', 'pera', 'uva']

for fruta in frutas:  # for -- in -- es para hacer una instrucción con cada elemento
    print(f'Me gusta la {fruta}')

# SOLO OPERADOR IN (da respuesta True o False)

print('pera' in frutas)
print('melón' in frutas)
print('manzana' in frutas)
print('patilla' in frutas)
print('uva' in frutas)
print('coco' in frutas)

# USANDO IN CON IF

if 'pera' in frutas:
    print('si tenemos pera')

else:
    print('no tenemos pera')

